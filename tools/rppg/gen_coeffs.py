"""Write firmware/src/dsp/bandpass_coeffs.h from the filter in pos.py.

Takes the frame rate and HR band from firmware/include/config.h. Rerun after
changing either one:
    python -m rppg.gen_coeffs
"""
import argparse
import re
import sys
from pathlib import Path

from scipy.signal import butter, lfilter_zi

from .pos import HR_BAND

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "firmware/include/config.h"
OUT = ROOT / "firmware/src/dsp/bandpass_coeffs.h"


def config_defines():
    """Numeric #defines from config.h, as strings."""
    return dict(re.findall(r"#define\s+(\w+)\s+([\d.]+)f?\b", CONFIG.read_text()))


def config_band(defs):
    """The HR band in config.h, in Hz."""
    return int(defs["HR_MIN_MHZ"]) / 1000, int(defs["HR_MAX_MHZ"]) / 1000


def arr(name, v):
    return f"static const double {name}[{len(v)}] = {{\n" + "".join(
        f"    {x:.17g},\n" for x in v) + "};\n"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--order", type=int, default=3)
    args = p.parse_args()

    defs = config_defines()
    fs = int(defs["FRAME_RATE_HZ"])
    band = config_band(defs)
    if band != HR_BAND:
        sys.exit(f"HR band differs: config.h {band}, pos.py {HR_BAND}. Make them match.")

    b, a = butter(args.order, [band[0] / (fs / 2), band[1] / (fs / 2)], btype="band")
    zi = lfilter_zi(b, a)
    OUT.write_text(
        "/* Generated by tools/rppg/gen_coeffs.py. Do not edit. */\n"
        f"/* Butterworth band-pass, order {args.order}, "
        f"{band[0]}-{band[1]} Hz at fs = {fs} Hz. */\n"
        "#ifndef BANDPASS_COEFFS_H\n#define BANDPASS_COEFFS_H\n\n"
        "/* Checked against config.h in rppg.c. */\n"
        f"#define BP_FS_HZ       {fs}\n"
        f"#define BP_HR_MIN_MHZ  {defs['HR_MIN_MHZ']}\n"
        f"#define BP_HR_MAX_MHZ  {defs['HR_MAX_MHZ']}\n"
        f"#define BP_TAPS        {len(b)}\n\n"
        + arr("bp_b", b) + "\n" + arr("bp_a", a) + "\n"
        "/* Steady-state initial conditions (scipy.signal.lfilter_zi). */\n"
        + arr("bp_zi", zi) + "\n#endif\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
