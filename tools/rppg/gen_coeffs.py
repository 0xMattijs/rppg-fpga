"""Write firmware/src/dsp/bandpass_coeffs.h from the filter in pos.py.

Rerun after changing the frame rate or HR band:
    python -m rppg.gen_coeffs --fs 30
"""
import argparse
from pathlib import Path

from scipy.signal import butter, lfilter_zi

from .pos import HR_BAND

OUT = Path(__file__).resolve().parents[2] / "firmware/src/dsp/bandpass_coeffs.h"


def arr(name, v):
    return f"static const double {name}[{len(v)}] = {{\n" + "".join(
        f"    {x:.17g},\n" for x in v) + "};\n"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--fs", type=float, default=30.0)
    p.add_argument("--order", type=int, default=3)
    args = p.parse_args()

    b, a = butter(args.order, [HR_BAND[0] / (args.fs / 2), HR_BAND[1] / (args.fs / 2)],
                  btype="band")
    zi = lfilter_zi(b, a)
    OUT.write_text(
        "/* Generated by tools/rppg/gen_coeffs.py. Do not edit. */\n"
        f"/* Butterworth band-pass, order {args.order}, "
        f"{HR_BAND[0]}-{HR_BAND[1]} Hz at fs = {args.fs} Hz. */\n"
        "#ifndef BANDPASS_COEFFS_H\n#define BANDPASS_COEFFS_H\n\n"
        f"#define BP_FS     {args.fs}\n#define BP_TAPS   {len(b)}\n\n"
        + arr("bp_b", b) + "\n" + arr("bp_a", a) + "\n"
        "/* Steady-state initial conditions (scipy.signal.lfilter_zi). */\n"
        + arr("bp_zi", zi) + "\n#endif\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
